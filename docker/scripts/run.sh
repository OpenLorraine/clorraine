#!/usr/bin/env bash
# Run a compiled Amiga program in FS-UAE and show the window on the host.
#
# Assembles build/run/ with the program and a generated Startup-Sequence,
# then boots it either from a directory hard drive (RUNNER=dir, default) or
# from a bootable ADF built with xdftool (RUNNER=adf).
#
# By default the program runs visibly on the Amiga screen. Set RUN_CAPTURE=1
# to redirect output to build/run/out.txt on the host instead (for automation).
#
# Usage:
#   scripts/run.sh <amiga-executable> [extra fs-uae arguments...]
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
docker_dir="$(dirname "${script_dir}")"
repo_dir="$(dirname "${docker_dir}")"
env_file="${docker_dir}/.env"

if [ ! -f "${env_file}" ]; then
    "${script_dir}/init-env.sh"
fi

runner_env="${RUNNER:-}"
debug_env="${RUN_DEBUG:-}"
capture_env="${RUN_CAPTURE:-}"

set -a
# shellcheck disable=SC1090
. "${env_file}"
set +a

# Explicit environment values win over .env, so `RUNNER=adf make run ...` works.
if [ -n "${runner_env}" ]; then RUNNER="${runner_env}"; fi
if [ -n "${debug_env}" ]; then RUN_DEBUG="${debug_env}"; fi
if [ -n "${capture_env}" ]; then RUN_CAPTURE="${capture_env}"; fi

if [ "$#" -lt 1 ]; then
    echo "usage: $0 <amiga-executable> [fs-uae arguments...]" >&2
    exit 2
fi

prog="$1"
shift

# Resolve the program relative to the repository root as well, so that
# `make run PROG=build/hello` works from the docker/ directory.
if [ ! -f "${prog}" ] && [ -f "${repo_dir}/${prog}" ]; then
    prog="${repo_dir}/${prog}"
fi

if [ ! -f "${prog}" ]; then
    echo "ERROR: program not found: ${prog}" >&2
    exit 2
fi
prog_abs="$(cd "$(dirname "${prog}")" && pwd)/$(basename "${prog}")"
prog_name="$(basename "${prog_abs}")"

run_dir="${repo_dir}/build/run"
rm -rf "${run_dir}"
mkdir -p "${run_dir}"
cp -f "${prog_abs}" "${run_dir}/${prog_name}"
rm -f "${run_dir}/out.txt"

if [ "${RUN_CAPTURE:-0}" = "1" ]; then
    cat > "${run_dir}/startup-sequence" <<EOF
; Generated by scripts/run.sh - do not edit.
CNEXT:${prog_name} >CNEXT:out.txt
EOF
else
    cat > "${run_dir}/startup-sequence" <<EOF
; Generated by scripts/run.sh - do not edit.
echo "c-next runner: ${prog_name}"
CNEXT:${prog_name}
echo "c-next runner: program returned"
EOF
fi

echo "runner:  ${run_dir}"
echo "program: ${prog_name}"
if [ "${RUN_CAPTURE:-0}" = "1" ]; then
    echo "output:  build/run/out.txt (captured)"
else
    echo "output:  visible in the emulator window (RUN_CAPTURE=1 to capture)"
fi

common_args=(
    --amiga-model="${AMIGA_MODEL}"
    --kickstart-file="${KICKSTART}"
)
if [ "${RUN_DEBUG:-0}" = "1" ]; then
    common_args+=(--console-debugger=1)
fi

case "${RUNNER:-dir}" in
    dir)
        exec "${script_dir}/emulator.sh" \
            "${common_args[@]}" \
            "--hard-drive-0=/work/build/run" \
            --hard-drive-0-label=CNEXT \
            --hard-drive-0-priority=0 \
            "$@"
        ;;
    adf)
        cd "${docker_dir}"
        docker compose -p cnext --env-file .env -f compose.yaml run --rm -T dev \
            bash -lc "xdftool /work/build/run.adf create + format CNEXT + write /work/build/run/${prog_name} ${prog_name} + makedir s + write /work/build/run/startup-sequence s + boot install"
        if [ "${RUN_CAPTURE:-0}" = "1" ]; then
            "${script_dir}/emulator.sh" \
                "${common_args[@]}" \
                "--floppy-drive-0=/work/build/run.adf" \
                "$@"
            docker compose -p cnext --env-file .env -f compose.yaml run --rm -T dev \
                xdftool /work/build/run.adf read out.txt /work/build/run >/dev/null 2>&1 \
                && echo "captured: build/run/out.txt (from ADF)" \
                || echo "no out.txt inside the ADF image"
        else
            exec "${script_dir}/emulator.sh" \
                "${common_args[@]}" \
                "--floppy-drive-0=/work/build/run.adf" \
                "$@"
        fi
        ;;
    *)
        echo "ERROR: unknown RUNNER='${RUNNER}' (expected dir or adf)" >&2
        exit 2
        ;;
esac
