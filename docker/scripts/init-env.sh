#!/usr/bin/env bash
# Create docker/.env with host-specific settings for the c-next SDK.
#
# Detects the X11 display and cookie, creates the Amiga data folder skeleton
# under $HOME/amiga, scans for Kickstart ROMs, and writes .env. The file is
# gitignored and contains only local paths.
#
# Usage:
#   scripts/init-env.sh           # create .env if missing
#   scripts/init-env.sh --force   # regenerate .env
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
docker_dir="$(dirname "${script_dir}")"
env_file="${docker_dir}/.env"

force=0
if [ "${1:-}" = "--force" ]; then
    force=1
fi

if [ -f "${env_file}" ] && [ "${force}" -eq 0 ]; then
    echo ".env already exists: ${env_file}"
    echo "Regenerate it with: make init FORCE=1"
    exit 0
fi

# Map a ROM filename to a likely Amiga model for FS-UAE.
rom_to_model() {
    local lower
    lower="$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')"
    case "${lower}" in
        *a1200*)                 echo A1200 ;;
        *a600*)                  echo A600 ;;
        *a3000*)                 echo A3000 ;;
        *a4000*)                 echo A4000 ;;
        *cd32*)                  echo CD32 ;;
        *a500*|*a1000*|*a2000*) echo A500 ;;
        *)                       echo A1200 ;;
    esac
}

# Find a usable X11 cookie file.
detect_xauthority() {
    if [ -n "${XAUTHORITY:-}" ] && [ -f "${XAUTHORITY}" ]; then
        printf '%s' "${XAUTHORITY}"
        return
    fi
    if [ -f "${HOME}/.Xauthority" ]; then
        printf '%s' "${HOME}/.Xauthority"
        return
    fi
    local found
    found="$(find "/run/user/$(id -u)" -maxdepth 2 -name Xauthority -type f 2>/dev/null | head -1 || true)"
    if [ -n "${found}" ]; then
        printf '%s' "${found}"
        return
    fi
    printf '%s' "${HOME}/.Xauthority"
}

display="${DISPLAY:-:0}"
xauthority="$(detect_xauthority)"
amiga_data="${AMIGA_DATA:-${HOME}/amiga}"

mkdir -p "${amiga_data}/roms" "${amiga_data}/adf" "${amiga_data}/hdf" "${amiga_data}/config"

kickstart="internal"
model="A1200"
suggestions=""

roms=()
while IFS= read -r line; do
    roms+=("${line}")
done < <(find "${amiga_data}/roms" -maxdepth 1 -type f -iname '*.rom' 2>/dev/null | sort)

if [ "${#roms[@]}" -eq 1 ]; then
    rom_name="$(basename "${roms[0]}")"
    kickstart="/amiga/roms/${rom_name}"
    model="$(rom_to_model "${rom_name}")"
    suggestions="# Using the only ROM found in ${amiga_data}/roms: ${rom_name}"
elif [ "${#roms[@]}" -gt 1 ]; then
    suggestions="# ROMs found in ${amiga_data}/roms; set KICKSTART and AMIGA_MODEL to use one:"
    for rom in "${roms[@]}"; do
        rom_name="$(basename "${rom}")"
        suggestions="${suggestions}"$'\n'"#   /amiga/roms/${rom_name} -> AMIGA_MODEL=$(rom_to_model "${rom_name}")"
    done
fi

cat > "${env_file}" <<EOF
# Generated by scripts/init-env.sh on $(date -Iseconds).
# Local configuration for the c-next SDK. Gitignored; regenerate with FORCE=1.

IMAGE=cnext-sdk:dev

# Host folder with Amiga test media, mounted read-only at /amiga.
AMIGA_DATA=${amiga_data}

# X11 display for the emulator window.
DISPLAY=${display}
XAUTHORITY=${xauthority}

${suggestions}
KICKSTART=${kickstart}
AMIGA_MODEL=${model}

FS_UAE_ARGS=
RUNNER=dir
RUN_CAPTURE=0
EOF

echo "created ${env_file}"
echo "  AMIGA_DATA=${amiga_data} (roms/, adf/, hdf/, config/)"
echo "  DISPLAY=${display}"
echo "  XAUTHORITY=${xauthority}"
echo "  KICKSTART=${kickstart}  AMIGA_MODEL=${model}"
if [ -n "${suggestions}" ]; then
    printf '%s\n' "${suggestions}" | sed 's/^/  /'
fi
if [ ! -f "${xauthority}" ]; then
    echo
    echo "WARNING: X11 cookie file not found: ${xauthority}"
    echo "The emulator window needs X11 access. Fix XAUTHORITY in ${env_file},"
    echo "or allow local clients with: xhost +local:"
fi
echo
echo "Next: put ROMs/ADFs in ${amiga_data}, then run 'make smoke' and 'make run PROG=...'."
